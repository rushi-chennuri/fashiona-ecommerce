export const getBadgeStyle = (badge) => {
  const styles = {
    new:        "bg-green-500 text-white",
    sale:       "bg-red-500 text-white",
    trending:   "bg-purple-600 text-white",
    bestseller: "bg-amber-500 text-white",
    hot:        "bg-orange-500 text-white",
    luxury:     "bg-yellow-600 text-white",
    summer:     "bg-blue-500 text-white",
    winter:     "bg-indigo-500 text-white",
  };
  return styles[badge] || "bg-gray-500 text-white";
};

export const formatPrice = (price) =>
  new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 }).format(price);

export const getDiscount = (price, original) =>
  Math.round((1 - price / original) * 100);
